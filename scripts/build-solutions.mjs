import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileSubjectModule } from './content/compiler.mjs';
import { SUBJECT_ORDER, loadAllSubjects } from './content/registry.mjs';

export async function buildSolutions({ outputDir = 'dist/solutions', check = false } = {}) {
  const targetDir = resolve(outputDir);
  const subjects = await loadAllSubjects();

  const fileMap = new Map();

  for (const { subject, questions, solutions } of subjects) {
    const filename = `${subject}-solutions.js`;
    const content = compileSubjectModule({ subject, questions, solutions });
    fileMap.set(filename, content);
  }

  // Generate index.js
  const importLines = [];
  const exportLines = [];
  const subjectEntries = [];

  for (const s of SUBJECT_ORDER) {
    importLines.push(`import {${s}Questions, ${s}Solutions} from './${s}-solutions.js';`);
    exportLines.push(`  ${s}Questions, ${s}Solutions,`);
    subjectEntries.push(`  ${s}: Object.freeze(attachSolutions(${s}Questions, ${s}Solutions)),`);
  }

  const indexContent = `// Generated by scripts/build-solutions.mjs. Do not edit.
${importLines.join('\n')}

export {
${exportLines.join('\n')}
};

function attachSolutions(questions, solutions) {
  return questions.map((q) => {
    const solution = (q.solutionRef && Object.prototype.hasOwnProperty.call(solutions, q.solutionRef))
      ? solutions[q.solutionRef]
      : null;
    return {...q, solution};
  });
}

export const writtenQuestionsBySubject = Object.freeze({
${subjectEntries.join('\n')}
});
`;
  fileMap.set('index.js', indexContent);

  if (check) {
    if (!existsSync(targetDir)) {
      throw new Error(`Generated content is stale: output directory ${relative(process.cwd(), targetDir)} does not exist`);
    }

    // Check all expected files
    for (const [filename, expectedContent] of fileMap.entries()) {
      const filePath = join(targetDir, filename);
      if (!existsSync(filePath)) {
        throw new Error(`Generated content is stale: ${filename} is missing in ${relative(process.cwd(), targetDir)}`);
      }
      const actualContent = readFileSync(filePath, 'utf8');
      if (actualContent !== expectedContent) {
        throw new Error(`Generated content is stale: ${filename} differs from compiled output`);
      }
    }

    // Check for unexpected extra .js files
    const existingFiles = readdirSync(targetDir);
    for (const file of existingFiles) {
      if (file.endsWith('.js') && !fileMap.has(file)) {
        throw new Error(`Generated content is stale: unexpected file ${file} in ${relative(process.cwd(), targetDir)}`);
      }
    }

    return {
      checked: true,
      fileCount: fileMap.size,
    };
  }

  mkdirSync(targetDir, { recursive: true });

  for (const [filename, content] of fileMap.entries()) {
    const filePath = join(targetDir, filename);
    writeFileSync(filePath, content, 'utf8');
  }

  return {
    written: true,
    fileCount: fileMap.size,
  };
}

const isMainModule = process.argv[1] && (
  resolve(process.argv[1]) === fileURLToPath(import.meta.url) ||
  process.argv[1].endsWith('build-solutions.mjs')
);

if (isMainModule) {
  const isCheck = process.argv.includes('--check');
  buildSolutions({ outputDir: 'dist/solutions', check: isCheck })
    .then((result) => {
      if (result.checked) {
        console.log(`Verified ${result.fileCount} generated solution files are up to date.`);
      } else {
        console.log(`Successfully generated ${result.fileCount} solution files in dist/solutions.`);
      }
    })
    .catch((err) => {
      console.error(err.message);
      process.exit(1);
    });
}
